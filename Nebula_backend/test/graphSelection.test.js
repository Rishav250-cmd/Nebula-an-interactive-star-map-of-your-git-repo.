test("graph selection prioritizes source files and records files left out", async () => {
  const root = await fixtureDirectory();
  try {
    const files = [];
    await mkdir(path.join(root, "src"));
    await mkdir(path.join(root, "tests"));
    for (let index = 0; index < 120; index += 1) {
      const file = `src/source-${String(index).padStart(3, "0")}.js`;
      files.push(file);
      await writeFile(path.join(root, file), `export const source${index} = ${index};\n`);
    }
    for (let index = 0; index < 60; index += 1) {
      const file = `tests/test-${String(index).padStart(3, "0")}.test.js`;
      files.push(file);
      await writeFile(path.join(root, file), `export const test${index} = ${index};\n`);
    }

    const result = runGraph(root, files, {
      MAX_CODE_FILES: "100",
      MAX_SOURCE_MB: "40",
      MAX_RSS_MB: "420",
    });
    assert.equal(result.meta.analyzedFiles, 100);
    assert.equal(result.meta.totalCodeFiles, 180);
    assert.equal(result.meta.truncated, true);
    assert.equal(result.meta.truncatedReason, "file-cap");
    assert.equal(result.meta.excludedTests, 60);
    assert.ok(result.nodes.every((file) => file.startsWith("src/")));
    assert.equal(result.meta.noEdges, true);
    assert.equal(result.meta.churnAvailable, false);
    assert.deepEqual(result.meta.history, { shallow: false, depth: 0 });
    assert.equal(result.meta.stale, false);
    assert.deepEqual(result.meta.languages, [{ ext: ".js", count: 180 }]);
    assert.ok(result.meta.analysisMs >= 0);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("graph skips generated, minified, binary, and oversized files with metadata", async () => {
  const root = await fixtureDirectory();
  try {
    const sources = {
      "src/normal.js": "export const normal = true;\n",
      "src/generated.js": "/* @generated: do not edit */\nexport const generated = true;\n",
      "src/do-not-edit.js": "// DO NOT EDIT: generated by a tool\nexport const generated = true;\n",
      "src/min.min.js": "export const minified = true;\n",
      "src/long-line.js": `const value = "${"x".repeat(5001)}";\n`,
      "src/bom.js": "\uFEFFexport const bom = true;\n",
      "src/binary.js": "\u0000\u0001binary",
      "src/large.js": "x".repeat(1024 * 1024 + 1),
    };
    for (const [file, content] of Object.entries(sources)) {
      await mkdir(path.dirname(path.join(root, file)), { recursive: true });
      await writeFile(path.join(root, file), content);
    }

    const result = runGraph(root, Object.keys(sources), { MAX_RSS_MB: "420" });
    assert.deepEqual(result.nodes, ["src/bom.js", "src/normal.js"]);
    assert.equal(result.meta.skipped.generated, 3);
    assert.equal(result.meta.skipped.binary, 1);
    assert.equal(result.meta.skipped.large, 1);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

