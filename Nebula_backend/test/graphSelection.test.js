test("Python-only repositories report extension counts in NO_SUPPORTED_FILES", async () => {
  const root = await fixtureDirectory();
  try {
    await writeFile(path.join(root, "main.py"), "print('hello')\n");
    const result = runGraph(root, ["main.py"], {});
    assert.deepEqual(result.error, {
      code: "NO_SUPPORTED_FILES",
      hint: "Nebula currently analyzes JavaScript and TypeScript",
      details: { languages: [{ ext: ".py", count: 1 }] },
    });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

async function fixtureDirectory() {
  return mkdtemp(path.join(os.tmpdir(), "nebula-graph-selection-"));
}

function runGraph(root, files, env) {
  const script = `
    import { buildGraph } from ${JSON.stringify(graphUrl)};
    try {
      const result = await buildGraph({
        id: "selection-fixture",
        dir: process.argv[1],
        files: JSON.parse(process.argv[2]),
        repoUrl: "selection-fixture.zip",
        getChurnImpl: async () => new Map(),
      });
      process.stdout.write(JSON.stringify({
        meta: result.graph.meta,
        nodes: result.graph.nodes.map(({ id }) => id),
        warnings: result.graph.warnings,
      }));
    } catch (error) {
      process.stdout.write(JSON.stringify({
        error: { code: error.code, hint: error.hint, details: error.details },
      }));
    }
  `;
  const stdout = execFileSync(
    process.execPath,
    ["--input-type=module", "-e", script, root, JSON.stringify(files)],
    { encoding: "utf8", env: { ...process.env, ...env } },
  );
  return JSON.parse(stdout);
}
